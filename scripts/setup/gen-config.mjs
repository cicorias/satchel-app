// Derives build-time config from config/app.config.json (the single source of truth)
// and config/local.config.json (gitignored: Team ID and other per-machine values).
//
// Outputs:
//   apple/Config/Generated.xcconfig   — consumed by apple/project.yml
//   config/local.config.json          — created on first run if Xcode knows the team
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const app = JSON.parse(readFileSync('config/app.config.json', 'utf8'));
const localPath = 'config/local.config.json';

function lookupTeamId(teamName) {
  try {
    const json = execFileSync(
      'sh',
      ['-c', 'defaults export com.apple.dt.Xcode - | plutil -extract IDEProvisioningTeamByIdentifier json -o - -'],
      { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] },
    );
    for (const teams of Object.values(JSON.parse(json))) {
      const hit = teams.find((t) => t.teamName === teamName);
      if (hit?.teamID) return hit.teamID;
    }
  } catch {
    // Not on a Mac, or Xcode has no accounts: fall through.
  }
  return undefined;
}

let local = existsSync(localPath) ? JSON.parse(readFileSync(localPath, 'utf8')) : {};
if (!local.apple?.developmentTeam && process.platform === 'darwin') {
  const id = lookupTeamId(app.apple.teamName);
  if (id) {
    local = { ...local, apple: { ...local.apple, developmentTeam: id } };
    writeFileSync(localPath, `${JSON.stringify(local, null, 2)}\n`);
    console.log(`wrote ${localPath} (team "${app.apple.teamName}" found in Xcode)`);
  }
}
const team = process.env.DEVELOPMENT_TEAM ?? local.apple?.developmentTeam ?? '';
if (!team) console.warn('warning: no Team ID — simulator builds work; device builds need config/local.config.json');

function buildNumber() {
  if (process.env.BUILD_NUMBER) return process.env.BUILD_NUMBER;
  try {
    return execFileSync('git', ['rev-list', '--count', 'HEAD'], {
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
    }).trim();
  } catch {
    return '0';
  }
}

const a = app.apple;
// "//" starts a comment in an xcconfig, so the site URL goes in without its scheme; Info.plist adds https://.
const siteHostPath = app.siteUrl.replace(/^https:\/\//, '').replace(/\/+$/, '');
const xcconfig = `// GENERATED by scripts/setup/gen-config.mjs from config/app.config.json — do not edit.
SATCHEL_APP_NAME = ${app.name}
SATCHEL_BUNDLE_ID = ${a.bundleId}
SATCHEL_SHARE_BUNDLE_ID = ${a.shareExtensionBundleId}
SATCHEL_SAFARI_BUNDLE_ID = ${a.safariExtensionBundleId}
SATCHEL_APP_GROUP = ${a.appGroup}
SATCHEL_ICLOUD_CONTAINER = ${a.iCloudContainer}
SATCHEL_KEYCHAIN_GROUP_SUFFIX = ${a.keychainGroupSuffix}
SATCHEL_URL_SCHEME = ${a.urlScheme}
SATCHEL_CLOUDKIT_ZONE = ${a.cloudKitZone}
SATCHEL_SITE = ${siteHostPath}
IPHONEOS_DEPLOYMENT_TARGET = ${a.deploymentTarget.iOS}
MARKETING_VERSION = ${app.version}
CURRENT_PROJECT_VERSION = ${buildNumber()}
DEVELOPMENT_TEAM = ${team}
`;
mkdirSync('apple/Config', { recursive: true });
writeFileSync('apple/Config/Generated.xcconfig', xcconfig);
console.log('wrote apple/Config/Generated.xcconfig');
